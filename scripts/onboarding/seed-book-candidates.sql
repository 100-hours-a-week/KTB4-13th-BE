-- A non-empty result identifies catalog mismatches. Do not replace missing books.
SELECT seed.book_id, seed.title AS expected_title, books.title AS actual_title
FROM onboarding_candidate_seed seed
LEFT JOIN books ON books.id = seed.book_id
WHERE books.id IS NULL OR CAST(books.title AS BINARY) <> CAST(seed.title AS BINARY);

-- One atomic INSERT: a catalog/code mismatch prevents the entire batch.
-- Window totals validate the batch while reading the temporary table only once.
INSERT INTO onboarding_book_candidates (subcategory_code, book_id, display_order)
SELECT verified.subcategory_code, verified.book_id, verified.display_order
FROM (
    SELECT seed.subcategory_code, seed.book_id, seed.display_order,
           COUNT(*) OVER () AS total_count,
           SUM(books.id IS NOT NULL
               AND CAST(books.title AS BINARY) = CAST(seed.title AS BINARY)
               AND options.id IS NOT NULL) OVER () AS matched_count
    FROM onboarding_candidate_seed seed
    LEFT JOIN books ON books.id = seed.book_id
    LEFT JOIN onboarding_options options
      ON options.onboarding_questions_id = 4 AND options.code = seed.subcategory_code
) verified
WHERE verified.total_count = 490 AND verified.matched_count = 490
ON DUPLICATE KEY UPDATE display_order = VALUES(display_order);

SELECT COUNT(*) AS matched_candidates
FROM onboarding_candidate_seed seed
JOIN onboarding_book_candidates candidate
  ON candidate.subcategory_code = seed.subcategory_code AND candidate.book_id = seed.book_id
WHERE candidate.display_order = seed.display_order;
