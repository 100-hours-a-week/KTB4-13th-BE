CREATE TABLE user_memories (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    type VARCHAR(16) NOT NULL,
    value VARCHAR(200) NOT NULL,
    strength TINYINT NOT NULL,
    categories JSON NOT NULL,
    keyword VARCHAR(100) NOT NULL,
    vector JSON NOT NULL,
    dim SMALLINT NOT NULL,
    conversation_id VARCHAR(200) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_user_memories_user_id FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_user_memories_type CHECK (type IN ('MOOD', 'TOPIC', 'AUTHOR', 'CONDITION')),
    CONSTRAINT ck_user_memories_strength CHECK (strength BETWEEN -3 AND 3 AND strength <> 0),
    CONSTRAINT ck_user_memories_categories CHECK (JSON_TYPE(categories) = 'ARRAY' AND JSON_LENGTH(categories) <= 3),
    CONSTRAINT ck_user_memories_keyword_not_blank CHECK (CHAR_LENGTH(TRIM(keyword)) >= 1),
    CONSTRAINT ck_user_memories_vector CHECK (JSON_TYPE(vector) = 'ARRAY' AND JSON_LENGTH(vector) = dim),
    CONSTRAINT ck_user_memories_dim CHECK (dim > 0),
    CONSTRAINT ck_user_memories_conversation_id_not_blank CHECK (CHAR_LENGTH(TRIM(conversation_id)) >= 1),
    INDEX idx_user_memories_user_id_deleted_at (user_id, deleted_at),
    INDEX idx_user_memories_user_id_conversation_id (user_id, conversation_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;
